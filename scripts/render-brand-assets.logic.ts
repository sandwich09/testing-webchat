/** An ICO file whose images are PNG frames (supported by every current browser). */
export function encodeIco(frames: readonly { size: number; png: Buffer }[]): Buffer {
  const header = Buffer.alloc(6);
  header.writeUInt16LE(0, 0); // reserved
  header.writeUInt16LE(1, 2); // type: icon
  header.writeUInt16LE(frames.length, 4);
  const entries: Buffer[] = [];
  let offset = 6 + 16 * frames.length;
  for (const f of frames) {
    if (f.size < 1 || f.size > 256)
      throw new Error(`ICO frame size ${String(f.size)} out of range`);
    const e = Buffer.alloc(16);
    e.writeUInt8(f.size === 256 ? 0 : f.size, 0); // width (0 means 256)
    e.writeUInt8(f.size === 256 ? 0 : f.size, 1); // height
    e.writeUInt8(0, 2); // no palette
    e.writeUInt8(0, 3); // reserved
    e.writeUInt16LE(1, 4); // colour planes
    e.writeUInt16LE(32, 6); // bits per pixel
    e.writeUInt32LE(f.png.length, 8);
    e.writeUInt32LE(offset, 12);
    offset += f.png.length;
    entries.push(e);
  }
  return Buffer.concat([header, ...entries, ...frames.map((f) => f.png)]);
}

/** Width and height of a PNG from its IHDR chunk. */
export function pngSize(png: Buffer): { width: number; height: number } {
  const signature = '89504e470d0a1a0a';
  if (png.subarray(0, 8).toString('hex') !== signature) throw new Error('not a PNG');
  return { width: png.readUInt32BE(16), height: png.readUInt32BE(20) };
}

/** The TypeScript module that carries the rich menu PNG for the LINE adapter, as base64. */
export function richMenuModule(png: Buffer): string {
  return [
    '// Generated by scripts/render-brand-assets.ts from scripts/brand/richmenu-3x1.html. Do not edit.',
    '// The PNG of public/brand/richmenu-3x1.png, carried in code so the server can upload it.',
    `export const RICH_MENU_IMAGE_PNG_BASE64 =\n  '${png.toString('base64')}';`,
    '',
  ].join('\n');
}
